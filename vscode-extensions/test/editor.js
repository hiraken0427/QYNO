'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const vscode = require('vscode');
async function run() {
    let checks = 0;
    const extension = vscode.extensions.getExtension('hiraken0427.qyno-vscode');
    assert.ok(extension); await extension.activate(); checks++;
    const uri = vscode.Uri.file(path.join(__dirname,'workspace/main.qy'));
    const document = await vscode.workspace.openTextDocument(uri);
    const editor = await vscode.window.showTextDocument(document);
    assert.equal(document.languageId,'qyno'); checks++;
    const completion = async (text) => {
        const line = 8, range = document.lineAt(line).range;
        await editor.edit(edit => edit.replace(range, text));
        const position = new vscode.Position(line,text.length);
        editor.selection = new vscode.Selection(position, position);
        const result = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider',uri,position);
        return result.items;
    };
    let items = await completion('\tmat');
    assert.ok(items.some(i=>i.label==='matrix')); checks++;
    items = await completion('\tfs.'); assert.ok(items.some(i=>i.label==='readline')); checks++;
    items = await completion('\tcircle.'); assert.ok(items.some(i=>i.label==='area')); checks++;
    items = await completion('\tmatrix[0].'); assert.ok(items.some(i=>i.label==='length')); checks++;
    items = await completion('\tio.input("入力> {mat'); assert.ok(items.some(i=>i.label==='matrix')); checks++;
    await completion('\tcircle.area(2.0)');
    const definitions = await vscode.commands.executeCommand('vscode.executeDefinitionProvider',uri,new vscode.Position(8,12));
    assert.ok(definitions.some(d=>(d.uri || d.targetUri).path.endsWith('/geometry/circle.qy'))); checks++;
    const hovers = await vscode.commands.executeCommand('vscode.executeHoverProvider',uri,new vscode.Position(8,12));
    assert.ok(hovers.length); checks++;
    await completion('\tfs.readline(source, ');
    const help = await vscode.commands.executeCommand('vscode.executeSignatureHelpProvider',uri,new vscode.Position(8,document.lineAt(8).text.length),'(',);
    assert.equal(help.activeParameter,1); assert.match(help.signatures[0].label,/ref str line/); checks++;
    const symbols = await vscode.commands.executeCommand('vscode.executeDocumentSymbolProvider',uri);
    assert.ok(symbols.some(s=>s.name==='main')); checks++;
    // Unsaved edits in both the active file and imported modules must be reflected.
    const target = await vscode.workspace.openTextDocument(vscode.Uri.file(path.join(__dirname,'workspace/geometry/circle.qy')));
    const edit = new vscode.WorkspaceEdit(); edit.insert(target.uri, new vscode.Position(target.lineCount-1,0),'double perimeter(double radius) = 2.0 * PI * radius\n');
    assert.ok(await vscode.workspace.applyEdit(edit));
    items = await completion('\tcircle.per'); assert.ok(items.some(i=>i.label==='perimeter')); checks++;
    const rename = new vscode.WorkspaceEdit(); rename.replace(uri,new vscode.Range(5,5,5,11),'grid');
    assert.ok(await vscode.workspace.applyEdit(rename));
    items = await completion('\tgri'); assert.ok(items.some(i=>i.label==='grid')); checks++;
    items = await completion('\tmat'); assert.ok(!items.some(i=>i.label==='matrix')); checks++;
    items = await completion('\t// fs.'); assert.ok(!items.some(i=>i.label==='readline')); checks++;
    const modelDoc = await vscode.workspace.openTextDocument({ language: 'qyno', content:
        'model Point;\n\tdouble x = 0.0\n\tdouble y = 0.0\n\tvoid move(double dx, double dy);\n\t\tthis.x += dx\n\t\tthis.y += dy\nint main();\n\tPoint p = {x=3.0, y=4.0}\n\tp.move(1.0, 2.0)\n\treturn 0\n' });
    await vscode.window.showTextDocument(modelDoc);
    const members = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', modelDoc.uri, new vscode.Position(8,3));
    assert.ok(members.items.some(i=>i.label==='x')); assert.ok(members.items.some(i=>i.label==='move')); checks++;
    const thisMembers = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider', modelDoc.uri, new vscode.Position(4,7));
    assert.ok(thisMembers.items.some(i=>i.label==='y')); checks++;
    const methodDefinitions = await vscode.commands.executeCommand('vscode.executeDefinitionProvider',modelDoc.uri,new vscode.Position(8,5));
    assert.ok(methodDefinitions.some(d=>(d.range || d.targetSelectionRange).start.line===3)); checks++;
    const methodHelp = await vscode.commands.executeCommand('vscode.executeSignatureHelpProvider',modelDoc.uri,new vscode.Position(8,14));
    assert.equal(methodHelp.activeParameter,1); assert.equal(methodHelp.signatures[0].label,'public void p.move(double dx, double dy)'); checks++;
    const modelOutline = await vscode.commands.executeCommand('vscode.executeDocumentSymbolProvider',modelDoc.uri);
    assert.ok(modelOutline.find(s=>s.name==='Point').children.some(s=>s.name==='move')); checks++;
    const visibilityDoc = await vscode.workspace.openTextDocument({ language: 'qyno', content:
        'model Counter;\n\tprivate int count = 7\n\tprivate void hidden();\n\t\tthis.count++\n\tpublic int current() = this.count\n\tpublic int other(Counter counter) = counter.count\nint main();\n\tCounter c\n\tc.hidden()\n\tc.count++\n\tc.current()\n\treturn 0\n' });
    await vscode.window.showTextDocument(visibilityDoc);
    const outside = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider',visibilityDoc.uri,new vscode.Position(10,3));
    assert.ok(outside.items.some(i=>i.label==='current')); assert.ok(!outside.items.some(i=>['count','hidden'].includes(i.label))); checks++;
    const inside = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider',visibilityDoc.uri,new vscode.Position(3,7));
    assert.ok(inside.items.some(i=>i.label==='count' && i.detail==='private int count')); assert.ok(inside.items.some(i=>i.label==='hidden')); checks++;
    const other = await vscode.commands.executeCommand('vscode.executeCompletionItemProvider',visibilityDoc.uri,new vscode.Position(5,visibilityDoc.lineAt(5).text.indexOf('counter.count') + 'counter.'.length));
    assert.ok(other.items.some(i=>i.label==='count')); checks++;
    const privateHover = await vscode.commands.executeCommand('vscode.executeHoverProvider',visibilityDoc.uri,new vscode.Position(9,5));
    assert.ok(privateHover.some(h=>h.contents.some(c=>c.value?.includes('private int count')))); checks++;
    const privateDefinition = await vscode.commands.executeCommand('vscode.executeDefinitionProvider',visibilityDoc.uri,new vscode.Position(9,5));
    assert.ok(privateDefinition.some(d=>(d.range || d.targetSelectionRange).start.line===1)); checks++;
    const visibilityOutline = await vscode.commands.executeCommand('vscode.executeDocumentSymbolProvider',visibilityDoc.uri);
    const counterOutline = visibilityOutline.find(s=>s.name==='Counter');
    assert.equal(counterOutline.children.find(s=>s.name==='count').detail,'private int count');
    assert.equal(counterOutline.children.find(s=>s.name==='current').detail,'public int current()'); checks++;
    const readonlyDoc = await vscode.workspace.openTextDocument({ language: 'qyno', content:
        'model Point;\n\tprivate int secret = 7\n\tdouble x\n\tint items[]\n\tpublic void move(double dx);\n\t\tthis.x += dx\n\tpublic readonly double distance() = this.x\n\tprivate readonly int hidden() = this.secret\n\tpublic readonly void inspect(ref readonly Point other);\n\t\tthis.distance()\n\t\tother.distance()\nint main();\n\tconst Point p = {}\n\tp.distance()\n\tio.print(p.items.length)\n\treturn 0\n' });
    await vscode.window.showTextDocument(readonlyDoc);
    const query = (line, prefix, command) => vscode.commands.executeCommand(command,readonlyDoc.uri,new vscode.Position(line,readonlyDoc.lineAt(line).text.indexOf(prefix)+prefix.length));
    const constMembers = await query(13,'p.','vscode.executeCompletionItemProvider');
    assert.ok(constMembers.items.some(i=>i.label==='distance')); assert.ok(!constMembers.items.some(i=>['move','secret','addr'].includes(i.label))); checks++;
    const readonlyThis = await query(9,'this.','vscode.executeCompletionItemProvider');
    assert.ok(readonlyThis.items.some(i=>i.label==='hidden')); assert.ok(!readonlyThis.items.some(i=>i.label==='move')); checks++;
    const readonlyOther = await query(10,'other.','vscode.executeCompletionItemProvider');
    assert.ok(readonlyOther.items.some(i=>i.label==='hidden')); assert.ok(!readonlyOther.items.some(i=>i.label==='move')); checks++;
    const arrayMembers = await query(14,'p.items.','vscode.executeCompletionItemProvider');
    assert.ok(arrayMembers.items.some(i=>i.label==='length')); assert.ok(!arrayMembers.items.some(i=>['add','clear','remove_at'].includes(i.label))); checks++;
    const readonlyHover = await query(13,'p.dis','vscode.executeHoverProvider');
    assert.ok(readonlyHover.some(h=>h.contents.some(c=>c.value?.includes('public readonly double distance()')))); checks++;
    const constHover = await query(13,'p','vscode.executeHoverProvider');
    assert.ok(constHover.some(h=>h.contents.some(c=>c.value?.includes('const Point p')))); checks++;
    const readonlyHelp = await query(13,'p.distance(','vscode.executeSignatureHelpProvider');
    assert.equal(readonlyHelp.signatures[0].label,'public readonly double p.distance()'); checks++;
    const readonlyOutline = await vscode.commands.executeCommand('vscode.executeDocumentSymbolProvider',readonlyDoc.uri);
    const readonlyPoint = readonlyOutline.find(s=>s.name==='Point');
    assert.equal(readonlyPoint.children.find(s=>s.name==='inspect').detail,'public readonly void inspect(ref readonly Point other)'); checks++;
    console.log(`QYNO VS Code integration: ${checks} checks passed`);
}
module.exports={run};
