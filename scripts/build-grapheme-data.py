#!/usr/bin/env python3
"""Build pinned Unicode 17.0 grapheme and White_Space properties without network IO."""
from pathlib import Path
root=Path(__file__).resolve().parent.parent
data=root/'unicode/17.0.0'
values=bytearray(0x110000)
properties={name:i for i,name in enumerate(['Other','CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT'])}
for filename in ['GraphemeBreakProperty.txt','emoji-data.txt','DerivedCoreProperties.txt']:
    for line in (data/filename).read_text().splitlines():
        fields=[s.strip() for s in line.split('#')[0].split(';')]
        if len(fields)<2: continue
        if filename.startswith('Grapheme'): flag=properties[fields[1]]
        elif filename.startswith('emoji'):
            if fields[1]!='Extended_Pictographic':continue
            flag=16
        else:
            if fields[1]!='InCB':continue
            flag={'Consonant':32,'Linker':64,'Extend':96}[fields[2]]
        bounds=fields[0].split('..');start=int(bounds[0],16);end=int(bounds[-1],16)
        for c in range(start,end+1):values[c]|=flag
ranges=[];start=0
for c in range(1,len(values)+1):
    if c==len(values) or values[c]!=values[start]:
        if values[start]:ranges.append((start,c-1,values[start]))
        start=c
output=['/* Unicode 17.0.0; generated by scripts/build-grapheme-data.py.',
        ' * Source data and license: unicode/17.0.0/. */',
        'static const struct { uint32_t first,last; unsigned property; } grapheme_ranges[] = {']
output += [f'    {{0x{a:x},0x{b:x},{flag}}},' for a,b,flag in ranges]
output += ['};']
white=[]
for line in (data/'PropList.txt').read_text().splitlines():
    fields=[s.strip() for s in line.split('#')[0].split(';')]
    if len(fields)<2 or fields[1]!='White_Space':continue
    bounds=fields[0].split('..');white.append((int(bounds[0],16),int(bounds[-1],16)))
assert sum(b-a+1 for a,b in white)==25
output += ['static const struct { uint32_t first,last; } white_space_ranges[] = {']
output += [f'    {{0x{a:x},0x{b:x}}},' for a,b in white]
output += ['};','']
(root/'grapheme_data.h').write_text('\n'.join(output))
print(f'Unicode 17.0.0: {len(ranges)} property ranges')
