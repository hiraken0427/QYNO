#!/usr/bin/env python3
"""Regenerate the OS-independent x64 numeric runtime using GCC and binutils.

Normal compiler builds use the checked-in header. No build tool is launched by
qyc or by a generated program. The image has no relocations or writable data.
"""
import os
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
cc = os.environ.get('CC', 'gcc')
with tempfile.TemporaryDirectory(prefix='qyno-wide-build-') as name:
    work = Path(name)
    obj, elf, binary = (work / f'runtime.{ext}' for ext in ('o', 'elf', 'bin'))
    subprocess.run([cc, '-std=c99', '-O2', '-fPIC', '-ffreestanding', '-fno-builtin',
                    '-fno-stack-protector', '-fno-asynchronous-unwind-tables', '-fno-jump-tables',
                    '-mno-red-zone', '-c', str(root / 'wide_runtime.c'), '-o', str(obj)], check=True)
    grapheme_obj=work/'grapheme.o'
    subprocess.run([cc,'-std=c99','-O2','-fPIC','-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-asynchronous-unwind-tables','-fno-jump-tables','-mno-red-zone','-c',str(root/'grapheme_runtime.c'),'-o',str(grapheme_obj)],check=True)
    script = work / 'runtime.ld'
    script.write_text('ENTRY(wide_execute)\nSECTIONS { . = 0; .text : { *(.text .text.*) *(.rodata .rodata.*) } /DISCARD/ : { *(.eh_frame*) *(.comment) *(.note*) } }\n')
    libgcc = subprocess.check_output([cc, '-print-libgcc-file-name'], text=True).strip()
    subprocess.run(['ld', '-T', str(script), '--gc-sections', '-o', str(elf), str(obj), str(grapheme_obj), libgcc], check=True)
    assert not subprocess.check_output(['nm', '-u', str(elf)]).strip(), 'unresolved runtime dependency'
    sections = subprocess.check_output(['size', str(elf)], text=True).splitlines()[-1].split()
    assert sections[1:3] == ['0', '0'], 'runtime must not have writable sections'
    symbols = subprocess.check_output(['nm', str(elf)], text=True).splitlines()
    entry = next(int(line.split()[0], 16) for line in symbols if line.endswith(' T wide_execute'))
    subprocess.run(['objcopy', '-O', 'binary', '--only-section=.text', str(elf), str(binary)], check=True)
    data = binary.read_bytes()
    output = ['/* Generated by scripts/build-wide-runtime.py; see licenses/libgcc/README.md. */',
              f'#define WIDE_ENTRY_OFFSET {entry}', 'static const unsigned char wide_blob[] = {']
    output += ['    ' + ','.join(f'0x{b:02x}' for b in data[i:i+16]) + ',' for i in range(0, len(data), 16)]
    output += ['};', '']
    (root / 'wide_blob.h').write_text('\n'.join(output))
    print(f'wide runtime: {len(data)} bytes, entry offset {entry}')
